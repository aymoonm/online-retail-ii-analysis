-- Calculate total revenue from normal sales only
Select 
	SUM(Quantity * Price) AS Total_Sales
From online_retail_cleaned
Where Transaction_Type = 'Sales';



-- Count unique invoices that contain normal sales transactions
SELECT 
    COUNT(DISTINCT Invoice) AS Total_Orders
FROM online_retail_cleaned
WHERE Transaction_Type = 'Sales';



-- Calculate the average revenue generated per normal sales order
SELECT 
    SUM(Quantity * Price) / COUNT(DISTINCT Invoice) AS Average_Order_Value
FROM online_retail_cleaned
WHERE Transaction_Type = 'Sales';



-- Calculate the monetary value associated with return/cancellation transactions
SELECT
    SUM(Quantity * Price) AS Return_Cancellation
FROM online_retail_cleaned
WHERE Transaction_Type = 'Return_Cancellation';



-- Calculate the percentage of sales value associated with returns/cancellations
SELECT
    (
        ABS(SUM(CASE 
            WHEN Transaction_Type = 'Return_Cancellation'
            THEN Quantity * Price
        END))
        /
        SUM(CASE 
            WHEN Transaction_Type = 'Sales'
            THEN Quantity * Price
        END)
    ) * 100 AS Return_Cancellation_Rate
FROM online_retail_cleaned;

-- Calculate monthly sales revenue to analyze the sales trend over time
Select 
	YEAR(InvoiceDate) AS Sales_Year,
	MONTH(InvoiceDate) AS Sales_Month,
	SUM(Quantity * Price) As Monthly_Sales
From online_retail_cleaned
Where Transaction_Type = 'Sales'
Group By
	YEAR(InvoiceDate),
	MONTH(InvoiceDate)
Order By
    Sales_Year ASC,
    Sales_Month ASC;



-- Find the month with the highest sales revenue
WITH MonthlySalesCTE AS (
    SELECT
        YEAR(InvoiceDate) AS Sales_Year,
        MONTH(InvoiceDate) AS Sales_Month,
        SUM(Quantity * Price) AS Total_Sales
    FROM online_retail_cleaned
    WHERE Transaction_Type = 'Sales'
    GROUP BY
        YEAR(InvoiceDate),
        MONTH(InvoiceDate)
)
SELECT TOP 1
    Sales_Year,
    Sales_Month,
    Total_Sales AS Highest_Monthly_Sales
FROM MonthlySalesCTE
ORDER BY Highest_Monthly_Sales DESC;


