-- Calculate total sales, UK sales, and the percentage of total sales generated by the United Kingdom
SELECT
    SUM(CASE 
        WHEN Country = 'United Kingdom' 
        THEN Quantity * Price 
        ELSE 0 
    END) AS UK_Sales,
    
    SUM(Quantity * Price) AS Total_Sales,
    
    (
        SUM(CASE 
            WHEN Country = 'United Kingdom' 
            THEN Quantity * Price 
            ELSE 0 
        END)
        / SUM(Quantity * Price)
    ) * 100 AS UK_Sales_Percentage
FROM online_retail_cleaned
WHERE Transaction_Type = 'Sales';



