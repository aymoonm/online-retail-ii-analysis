ORDER BY Orders_Per_Customer DESC;



-- Classify customers by the number of orders they made in the United Kingdom
WITH CustomerOrders AS (
    SELECT
        Customer_ID,
        COUNT(DISTINCT Invoice) AS Total_Orders
    FROM online_retail_cleaned
    WHERE Transaction_Type = 'Sales'
        AND Country = 'United Kingdom'
        AND Customer_ID IS NOT NULL
    GROUP BY Customer_ID
)
SELECT
    CASE
        WHEN Total_Orders = 1 THEN '1 Order'
        WHEN Total_Orders BETWEEN 2 AND 5 THEN '2-5 Orders'
        WHEN Total_Orders BETWEEN 6 AND 10 THEN '6-10 Orders'
        ELSE '10+ Orders'
    END AS Customer_Order_Frequency,
    COUNT(*) AS Number_of_Customers
FROM CustomerOrders
GROUP BY
    CASE
        WHEN Total_Orders = 1 THEN '1 Order'
        WHEN Total_Orders BETWEEN 2 AND 5 THEN '2-5 Orders'
        WHEN Total_Orders BETWEEN 6 AND 10 THEN '6-10 Orders'
        ELSE '10+ Orders'
    END
ORDER BY Number_of_Customers DESC;




-- Compare sales contribution between one-time and repeat customers in the UK
WITH CustomerOrders AS (
    SELECT
        Customer_ID,
        COUNT(DISTINCT Invoice) AS Total_Orders
    FROM online_retail_cleaned
    WHERE Transaction_Type = 'Sales'
        AND Country = 'United Kingdom'
        AND Customer_ID IS NOT NULL
    GROUP BY Customer_ID
)
SELECT
    CASE
        WHEN co.Total_Orders = 1 THEN 'One-Time Customer'
        ELSE 'Repeat Customer'
    END AS Customer_Type,
    SUM(r.Quantity * r.Price) AS Total_Sales
FROM online_retail_cleaned AS r
INNER JOIN CustomerOrders AS co
    ON r.Customer_ID = co.Customer_ID
WHERE r.Transaction_Type = 'Sales'
    AND r.Country = 'United Kingdom'
GROUP BY
    CASE
        WHEN co.Total_Orders = 1 THEN 'One-Time Customer'
        ELSE 'Repeat Customer'
    END
ORDER BY Total_Sales DESC;



-- Compare the number of customers and repeat customers across countries
-- to identify whether strong customer retention is unique to the United Kingdom
WITH CustomerOrders AS (
    SELECT
        Country,
        Customer_ID,
        COUNT(DISTINCT Invoice) AS Total_Orders
    FROM online_retail_cleaned
    WHERE Transaction_Type = 'Sales'
        AND Customer_ID IS NOT NULL
    GROUP BY
        Country,
        Customer_ID
)
SELECT
    Country,
    COUNT(*) AS Total_Customers,
    SUM(CASE WHEN Total_Orders > 1 THEN 1 ELSE 0 END) AS Repeat_Customers,
    (
        SUM(CASE WHEN Total_Orders > 1 THEN 1 ELSE 0 END) * 100.0
        / COUNT(*)
    ) AS Repeat_Customer_Rate
FROM CustomerOrders
GROUP BY Country
HAVING COUNT(*) >= 20
ORDER BY Repeat_Customer_Rate DESC;