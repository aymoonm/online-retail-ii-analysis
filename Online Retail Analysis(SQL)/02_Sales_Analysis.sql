-- Calculate the average number of orders per customer in each country
SELECT
    Country,
    COUNT(DISTINCT Customer_ID) AS Unique_Customers,
    COUNT(DISTINCT Invoice) AS Total_Orders,
    COUNT(DISTINCT Invoice) * 1.0 / COUNT(DISTINCT [Customer_ID]) AS Orders_Per_Customer
